def add_table(doc: Document, headers: list[str], rows: list[list[str]], font: str) -> None:
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    table.autofit = False
    widths = [1.45, 2.15, 2.7] if len(headers) == 3 else [1.7] * len(headers)
    total = sum(widths)
    widths = [w / total * 6.35 for w in widths]
    for idx, header in enumerate(headers):
        cell = table.rows[0].cells[idx]
        cell.width = Inches(widths[idx])
        cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        set_cell_shading(cell, "E8F1F8")
        set_cell_text(cell, header, bold=True, color="17324D")
    for row in rows:
        cells = table.add_row().cells
        for idx, value in enumerate(row):
            cells[idx].width = Inches(widths[idx])
            cells[idx].vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if idx == 0:
                set_cell_shading(cells[idx], "F6F8FA")
            set_cell_text(cells[idx], value, bold=idx == 0)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def add_note(doc: Document, text: str, font: str, label: str) -> None:
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.cell(0, 0)
    set_cell_shading(cell, "FFF8E6")
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(0)
    r1 = p.add_run(label + " ")
    r1.bold = True
    r1.font.color.rgb = RGBColor(122, 90, 0)
    set_run_font(r1, font)
    r2 = p.add_run(text)
    set_run_font(r2, font)
    r1.font.size = Pt(9.5)
    r2.font.size = Pt(9.5)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def setup_styles(doc: Document, font: str) -> None:
    styles = doc.styles
    normal = styles["Normal"]
    normal.font.name = font
    normal.font.size = Pt(10.5)
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), font)

    for name, size, color, before, after in [
        ("Title", 24, "0B2545", 0, 8),
        ("Subtitle", 11, "546A7B", 0, 16),
        ("Heading 1", 16, "0B4F7A", 16, 6),
        ("Heading 2", 13, "17324D", 12, 4),
        ("Heading 3", 11, "17324D", 8, 4),
    ]:
        style = styles[name]
        style.font.name = font
        style.font.size = Pt(size)
        style.font.color.rgb = RGBColor.from_string(color)
        style._element.rPr.rFonts.set(qn("w:eastAsia"), font)
        style.paragraph_format.space_before = Pt(before)
        style.paragraph_format.space_after = Pt(after)


def add_footer(doc: Document, text: str, font: str) -> None:
    section = doc.sections[0]
    footer = section.footer
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    set_run_font(r, font)
    r.font.size = Pt(8)
    r.font.color.rgb = RGBColor(100, 116, 139)


def build_manual(data: dict) -> Path:
    doc = Document()
    section = doc.sections[0]
    section.page_width = Inches(8.5)
    section.page_height = Inches(11)
    section.top_margin = Inches(0.78)
    section.bottom_margin = Inches(0.72)
    section.left_margin = Inches(0.82)
    section.right_margin = Inches(0.82)

    font = data["font"]
    setup_styles(doc, font)
    add_footer(doc, data["title"], font)

    title = doc.add_paragraph(style="Title")
    title.alignment = WD_ALIGN_PARAGRAPH.LEFT
    run = title.add_run(data["title"])
    set_run_font(run, font)
    run.bold = True

    subtitle = doc.add_paragraph(style="Subtitle")
    subtitle.add_run(data["subtitle"])
    set_paragraph_font(subtitle, font, 11)

    meta = doc.add_paragraph()
    meta.paragraph_format.space_after = Pt(14)
    meta_run = meta.add_run(data["meta"])
    set_run_font(meta_run, font)
    meta_run.font.size = Pt(9)
    meta_run.font.color.rgb = RGBColor(100, 116, 139)

    for paragraph in data["intro"]:
        add_para(doc, paragraph, font, after=6)

    add_note(doc, "建议把本手册和动作命名规则发给所有参与编课的人，避免同一动作出现多个名字或多个分类。"
             if data is ZH else
             "Рекомендуется передать это руководство всем, кто готовит курсы, чтобы избежать разных названий одного упражнения и лишних категорий.",
             font, "提示：" if data is ZH else "Совет:")

    for section_data in data["sections"]:
        doc.add_heading(section_data["h"], level=1)
        for paragraph in section_data.get("body", []):
            add_para(doc, paragraph, font, after=5)
        if "steps" in section_data:
            for idx, step in enumerate(section_data["steps"], start=1):
                add_step(doc, idx, step, font)
        if "table" in section_data:
            add_table(doc, section_data["table"]["headers"], section_data["table"]["rows"], font)
        if "note" in section_data:
            add_note(doc, section_data["note"], font, "注意：" if data is ZH else "Важно:")

    path = OUT_DIR / data["filename"]
    doc.save(path)
    return path


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for item in (ZH, RU):
        path = build_manual(item)
        print(path)


if __name__ == "__main__":
    main()
